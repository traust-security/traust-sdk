// Command insights generates v1/traust/insights.gen.go: each view contract's generated type
// bound to its ViewName, so GetInsightAs[T] asks core for the view T decodes.
// Usage: go run ./internal/generate/insights <client.gen.go> <views-openapi.json> <insights.gen.go>
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"log"
	"os"
	"regexp"
	"sort"
)

var viewConst = regexp.MustCompile(`(?m)^\s+(\w+)\s+ViewName = "([^"]+)"$`)

func main() {
	if len(os.Args) != 4 {
		log.Fatal("usage: insights <client.gen.go> <views-openapi.json> <insights.gen.go>")
	}
	client, err := os.ReadFile(os.Args[1])
	if err != nil {
		log.Fatal(err)
	}
	constants := map[string]string{}
	for _, m := range viewConst.FindAllStringSubmatch(string(client), -1) {
		constants[m[2]] = m[1]
	}
	raw, err := os.ReadFile(os.Args[2])
	if err != nil {
		log.Fatal(err)
	}
	var doc struct {
		Insights map[string]string `json:"x-traust-insights"`
	}
	if err := json.Unmarshal(raw, &doc); err != nil {
		log.Fatal(err)
	}
	types := make([]string, 0, len(doc.Insights))
	for name := range doc.Insights {
		types = append(types, name)
	}
	sort.Strings(types)
	var out bytes.Buffer
	out.WriteString("// Code generated by internal/generate/insights; DO NOT EDIT.\n\npackage traust\n")
	for _, name := range types {
		view := doc.Insights[name]
		constant, ok := constants[view]
		if !ok {
			log.Fatalf("view %q has a contract but no ViewName in core's OpenAPI", view)
		}
		fmt.Fprintf(&out, "\nfunc (*%s) insightName() ViewName { return %s }\n", name, constant)
	}
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(os.Args[3], formatted, 0o644); err != nil {
		log.Fatal(err)
	}
}
