// Command insights generates the binding between each view contract's generated type and its
// ViewName: v1/traust/insights.gen.go binds the type inside the root (GetInsightAs[T] asks
// core for the view T decodes), and v1/traust/insight/insights.gen.go carries the same map to
// the insight package, whose report reader reads it through viewName.
// Usage: go run ./internal/generate/insights <client.gen.go> <views-openapi.json> <insights.gen.go> <insight/insights.gen.go>
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"log"
	"os"
	"regexp"
	"sort"
)

var viewConst = regexp.MustCompile(`(?m)^\s+(\w+)\s+ViewName = "([^"]+)"$`)

// The root package's import path, the one the insight package reads the view types through.
const rootImport = "github.com/traust-security/traust-sdk/go/v1/traust"

func main() {
	if len(os.Args) != 5 {
		log.Fatal("usage: insights <client.gen.go> <views-openapi.json> <insights.gen.go> <insight/insights.gen.go>")
	}
	client, err := os.ReadFile(os.Args[1])
	if err != nil {
		log.Fatal(err)
	}
	constants := map[string]string{}
	for _, m := range viewConst.FindAllStringSubmatch(string(client), -1) {
		constants[m[2]] = m[1]
	}
	raw, err := os.ReadFile(os.Args[2])
	if err != nil {
		log.Fatal(err)
	}
	var doc struct {
		Insights map[string]string `json:"x-traust-insights"`
	}
	if err := json.Unmarshal(raw, &doc); err != nil {
		log.Fatal(err)
	}
	bindings := make([][2]string, 0, len(doc.Insights))
	for name, view := range doc.Insights {
		constant, ok := constants[view]
		if !ok {
			log.Fatalf("view %q has a contract but no ViewName in core's OpenAPI", view)
		}
		bindings = append(bindings, [2]string{name, constant})
	}
	sort.Slice(bindings, func(i, j int) bool { return bindings[i][0] < bindings[j][0] })

	var root bytes.Buffer
	root.WriteString("// Code generated by internal/generate/insights; DO NOT EDIT.\n\npackage traust\n")
	for _, binding := range bindings {
		fmt.Fprintf(&root, "\nfunc (*%s) insightName() ViewName { return %s }\n", binding[0], binding[1])
	}
	if err := writeFormatted(os.Args[3], root.Bytes()); err != nil {
		log.Fatal(err)
	}

	var insight bytes.Buffer
	insight.WriteString("// Code generated by internal/generate/insights; DO NOT EDIT.\n\npackage insight\n\nimport ")
	insight.WriteString(fmt.Sprintf("%q\n\n", rootImport))
	insight.WriteString("// viewName is the view the type decodes: the typed key the report reader checks a\n")
	insight.WriteString("// report against, \"\" for a type no contract names.\n")
	insight.WriteString("func viewName[T any](view T) traust.ViewName {\n\tswitch any(view).(type) {\n")
	for _, binding := range bindings {
		fmt.Fprintf(&insight, "\tcase traust.%s:\n\t\treturn traust.%s\n", binding[0], binding[1])
	}
	insight.WriteString("\tdefault:\n\t\treturn \"\"\n\t}\n}\n")
	if err := writeFormatted(os.Args[4], insight.Bytes()); err != nil {
		log.Fatal(err)
	}
}

func writeFormatted(path string, source []byte) error {
	formatted, err := format.Source(source)
	if err != nil {
		return err
	}
	return os.WriteFile(path, formatted, 0o644) // #nosec G306 -- generated source, world-readable like every source file
}
